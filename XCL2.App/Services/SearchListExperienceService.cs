using System.Collections;
using System.ComponentModel;
using System.Reflection;
using System.Runtime.CompilerServices;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Controls.Primitives;
using System.Windows.Data;
using XCL2.App.Models;

namespace XCL2.App.Services;

/// <summary>Small local table options, exposed only on table headers. Existing cell menus are retained.</summary>
public static class SearchListExperienceService
{
    private static Func<AppConfig>? _config;
    private static Action? _save;
    private static bool _initialized;
    private static readonly ConditionalWeakTable<DataGrid, GridState> States = new();
    private sealed class GridState
    {
        public readonly Dictionary<DataGridColumn, Visibility> Defaults = new();
        public readonly Dictionary<object, int> Order = new(ReferenceEqualityComparer.Instance);
    }
    public static void Initialize(Func<AppConfig> config, Action save)
    {
        _config = config; _save = save;
        if (_initialized) return;
        _initialized = true;
        EventManager.RegisterClassHandler(typeof(DataGrid), FrameworkElement.LoadedEvent, new RoutedEventHandler(Loaded));
    }
    private static void Loaded(object sender, RoutedEventArgs e)
    {
        if (sender is not DataGrid grid || States.TryGetValue(grid, out _)) return;
        var state = new GridState();
        States.Add(grid, state);
        void CaptureColumns()
        {
            foreach (var column in grid.Columns) state.Defaults.TryAdd(column, column.Visibility);
            string key = Key(grid);
            var hiddenColumns = _config?.Invoke().Ux50TableHiddenColumns;
            if (!string.IsNullOrEmpty(grid.Name) && hiddenColumns != null && hiddenColumns.TryGetValue(key, out var hidden))
            {
                foreach (var column in grid.Columns.Where(column => hidden?.Contains(ColumnKey(grid, column)) == true))
                    column.SetCurrentValue(DataGridColumn.VisibilityProperty, Visibility.Collapsed);
                if (!grid.Columns.Any(column => column.Visibility == Visibility.Visible))
                    foreach (var pair in state.Defaults) pair.Key.SetCurrentValue(DataGridColumn.VisibilityProperty, pair.Value);
            }
        }
        CaptureColumns();
        grid.AutoGeneratedColumns += (_, _) => CaptureColumns();
        grid.Columns.CollectionChanged += (_, _) => CaptureColumns();
        grid.AddHandler(ContextMenuService.ContextMenuOpeningEvent, new ContextMenuEventHandler((_, args) =>
        {
            // A cell's right-click actions belong to that cell; show columns only on a header.
            if (args.Handled || args.OriginalSource is not DependencyObject source || FindHeader(source) is not DataGridColumnHeader header) return;
            if (source is not FrameworkElement target || grid.Columns.Count == 0) return;
            var originalMenu = header.ContextMenu ?? grid.ContextMenu;
            var menu = originalMenu ?? new ContextMenu();
            foreach (var old in menu.Items.OfType<MenuItem>().Where(item => Equals(item.Tag, "XCL2.Columns")).ToArray()) menu.Items.Remove(old);
            var columns = new MenuItem { Header = "显示的列", Tag = "XCL2.Columns" };
            foreach (var column in grid.Columns.OrderBy(column => column.DisplayIndex))
            {
                var label = column.Header as string ?? (column.Header as TextBlock)?.Text ?? column.SortMemberPath;
                if (string.IsNullOrWhiteSpace(label)) label = $"第 {grid.Columns.IndexOf(column) + 1} 列";
                var option = new MenuItem { Header = label.Replace("_", "__"), IsCheckable = true,
                    IsChecked = column.Visibility == Visibility.Visible,
                    IsEnabled = column.Visibility != Visibility.Visible || grid.Columns.Count(c => c.Visibility == Visibility.Visible) > 1 };
                option.Click += (_, _) =>
                {
                    column.SetCurrentValue(DataGridColumn.VisibilityProperty, option.IsChecked ? Visibility.Visible : Visibility.Collapsed);
                    Persist(grid);
                };
                columns.Items.Add(option);
            }
            var reset = new MenuItem { Header = "恢复默认列" };
            reset.Click += (_, _) => { foreach (var pair in state.Defaults) pair.Key.SetCurrentValue(DataGridColumn.VisibilityProperty, pair.Value); Persist(grid); };
            columns.Items.Add(new Separator()); columns.Items.Add(reset);
            menu.Items.Add(columns);
            if (originalMenu != null) return;
            menu.PlacementTarget = target;
            menu.IsOpen = true;
            args.Handled = true;
        }), true);
        grid.Sorting += (_, args) => StableSort(grid, state, args);
    }
    private static DataGridColumnHeader? FindHeader(DependencyObject? node)
    {
        for (; node != null; node = node is System.Windows.Media.Visual or System.Windows.Media.Media3D.Visual3D
            ? System.Windows.Media.VisualTreeHelper.GetParent(node) : LogicalTreeHelper.GetParent(node))
            if (node is DataGridColumnHeader header) return header;
        return null;
    }
    private static void StableSort(DataGrid grid, GridState state, DataGridSortingEventArgs args)
    {
        if (_config?.Invoke().Ux50SearchStableSort != true || args.Handled || !grid.IsReadOnly
            || string.IsNullOrWhiteSpace(args.Column.SortMemberPath)
            || KeyboardModifiers() || grid.ItemsSource == null) return;
        // Leave editable/remote/grouped/custom views with their original sorting implementation.
        if (CollectionViewSource.GetDefaultView(grid.ItemsSource) is not ListCollectionView view
            || view.GroupDescriptions.Count != 0 || view.IsAddingNew || view.IsEditingItem
            || (view.CustomSort != null && view.CustomSort is not StableComparer)) return;
        string path = args.Column.SortMemberPath;
        if (path.Contains('.') || path.Contains('[')) return;
        var rows = view.SourceCollection.Cast<object>().Where(row => row != null && row != CollectionView.NewItemPlaceholder).ToArray();
        if (rows.Length == 0 || rows.Length > 10000) return;
        var property = rows[0].GetType().GetProperty(path, BindingFlags.Public | BindingFlags.Instance);
        if (property == null || property.GetIndexParameters().Length != 0) return;
        // Stable ties use the current source order, rather than the reversed previous display order.
        state.Order.Clear();
        for (int index = 0; index < rows.Length; ++index) state.Order.TryAdd(rows[index], index);
        var direction = args.Column.SortDirection == ListSortDirection.Ascending ? ListSortDirection.Descending : ListSortDirection.Ascending;
        foreach (var column in grid.Columns) column.SortDirection = null;
        args.Column.SortDirection = direction;
        view.CustomSort = new StableComparer(property, direction == ListSortDirection.Descending, state.Order);
        args.Handled = true;
    }
    private static bool KeyboardModifiers() => System.Windows.Input.Keyboard.Modifiers != System.Windows.Input.ModifierKeys.None;
    private sealed class StableComparer(PropertyInfo property, bool descending, Dictionary<object, int> order) : IComparer
    {
        public int Compare(object? left, object? right)
        {
            if (ReferenceEquals(left, right)) return 0;
            object? a = null, b = null;
            try { a = left == null ? null : property.GetValue(left); b = right == null ? null : property.GetValue(right); }
            catch { /* A heterogeneous view keeps its stable order instead of throwing from WPF layout. */ }
            int result;
            try { result = Comparer.DefaultInvariant.Compare(a, b); }
            catch { result = string.Compare(a?.ToString(), b?.ToString(), StringComparison.OrdinalIgnoreCase); }
            if (result != 0) return descending ? (result < 0 ? 1 : -1) : result;
            return (left != null && order.TryGetValue(left, out var x) ? x : int.MaxValue)
                .CompareTo(right != null && order.TryGetValue(right, out var y) ? y : int.MaxValue);
        }
    }
    private static string Key(DataGrid grid)
    {
        DependencyObject? owner = grid;
        while (owner != null && owner is not UserControl && owner is not Window)
            owner = LogicalTreeHelper.GetParent(owner);
        return (owner?.GetType().FullName ?? "page") + "/" + grid.Name;
    }
    private static string ColumnKey(DataGrid grid, DataGridColumn column) => !string.IsNullOrWhiteSpace(column.SortMemberPath)
        ? column.SortMemberPath : grid.Columns.IndexOf(column).ToString(System.Globalization.CultureInfo.InvariantCulture);
    private static void Persist(DataGrid grid)
    {
        if (_config == null || string.IsNullOrEmpty(grid.Name)) return;
        var config = _config(); config.Ux50TableHiddenColumns ??= new();
        config.Ux50TableHiddenColumns[Key(grid)] = grid.Columns.Where(column => column.Visibility != Visibility.Visible).Select(column => ColumnKey(grid, column)).ToList();
        try { _save?.Invoke(); } catch (Exception ex) { LauncherLogService.AppendLine("[表格列] 保存失败：" + ex.Message); }
    }
}
