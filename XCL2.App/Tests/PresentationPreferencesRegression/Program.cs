using System.Globalization;
using XCL2.App.Models;
using XCL2.App.Services;

CultureInfo.CurrentCulture = CultureInfo.GetCultureInfo("en-US");
var count = 0;
void Check(bool passed, string message) { if (!passed) throw new InvalidOperationException(message); count++; }
var cfg = new AppConfig();
const string address = "private.example:25565";
Check(PresentationPreferencesService.FormatServerAddress(address, cfg) == address, "default keeps existing server display");
cfg.HideServerAddresses = true;
Check(PresentationPreferencesService.FormatServerAddress(address, cfg) == "地址已隐藏", "privacy display masks endpoint");
Check(address == "private.example:25565", "display formatting does not modify stored connection data");
Check(PresentationPreferencesService.FormatServerAddress(null, new()) == "", "missing endpoint remains blank");
Check(cfg.RememberWindowPlacement && cfg.FollowSystemReducedMotion, "position recovery and OS motion preference default enabled");
Check(cfg.PreferredTimeFormat == LauncherTimeFormat.System && cfg.PreferredCapacityUnit == LauncherCapacityUnit.Automatic, "format preferences follow system/automatic by default");
Check(PresentationPreferencesService.FormatCapacity(1, cfg).StartsWith("< 0.01\u00A0MB"), "nonempty tiny files are not displayed as zero bytes");
Check(PresentationPreferencesService.FormatCapacity(1048576, cfg) == "1\u00A0MB", "binary megabytes display accurately");
Check(PresentationPreferencesService.FormatCapacity(1073741824, cfg) == "1\u00A0GB", "automatic unit switches at one GiB");
cfg.PreferredCapacityUnit = LauncherCapacityUnit.MB;
Check(PresentationPreferencesService.FormatCapacity(1073741824, cfg) == "1024\u00A0MB", "explicit megabytes override automatic unit");
cfg.PreferredCapacityUnit = LauncherCapacityUnit.GB;
Check(PresentationPreferencesService.FormatCapacity(536870912, cfg) == "0.5\u00A0GB", "explicit gigabytes preserves fractional size");
cfg.ShowExactCapacityValues = true;
Check(PresentationPreferencesService.FormatCapacity(1048576, cfg).Contains("1,048,576\u00A0字节"), "optional exact byte count stays distinguishable");
Check(!PresentationPreferencesService.FormatCapacity(-1, cfg).Contains("-"), "negative lengths never display negative capacity");
var date = new DateTimeOffset(2026, 10, 17, 13, 5, 0, TimeSpan.Zero);
Check(PresentationPreferencesService.FormatDateTime(date, cfg) == date.ToLocalTime().ToString("g", CultureInfo.CurrentCulture), "system date format uses local timezone");
cfg.PreferredTimeFormat = LauncherTimeFormat.TwentyFourHour;
Check(PresentationPreferencesService.FormatDateTime(date, cfg).EndsWith(date.ToLocalTime().ToString("HH:mm")), "24-hour preference is applied");
cfg.PreferredTimeFormat = LauncherTimeFormat.TwelveHour;
Check(PresentationPreferencesService.FormatDateTime(date, cfg).EndsWith(date.ToLocalTime().ToString("h:mm tt", CultureInfo.CurrentCulture)), "12-hour preference is applied");
Check(PresentationPreferencesService.FormatDateTime("invalid-date", cfg) == "invalid-date", "unknown source date remains inspectable");
Check(PresentationPreferencesService.FormatFullDateTime(date, cfg).Contains(TimeZoneInfo.Local.Id), "full timestamp identifies local timezone");
cfg.Ux50FullTimeTooltips = false;
Check(PresentationPreferencesService.FormatFullDateTime(date, cfg) == PresentationPreferencesService.FormatDateTime(date, cfg), "full time tooltip can be disabled");
Check(PresentationPreferencesService.FormatNumberWithUnit(2, "GB", config: cfg) == "2\u00A0GB", "numeric display avoids isolated unit wrapping");
cfg.Ux50UniformNumberSpacing = false;
cfg.PreferredCapacityUnit = LauncherCapacityUnit.MB;
Check(PresentationPreferencesService.FormatCapacity(1048576, cfg) == "1 MB（1,048,576 字节）", "shared capacity and exact bytes honor ordinary spacing when disabled");
Check(!PresentationPreferencesService.FormatCapacity(1048576, cfg).Contains("\u00A0"), "capacity formatter really applies spacing preference");
Check(PresentationPreferencesService.FormatNumberWithUnit(2, "GB", config: cfg) == "2 GB", "unit formatting can return to ordinary spacing");
var notifications = 0;
void Changed() => notifications++;
PresentationPreferencesService.Changed += Changed;
PresentationPreferencesService.NotifyChanged();
PresentationPreferencesService.Changed -= Changed;
PresentationPreferencesService.NotifyChanged();
Check(notifications == 1, "view subscriptions can detach without retained notifications");
cfg.FeatureSearchWidth = 400; cfg.FeatureSearchHeight = 80; cfg.FeatureSearchOffsetX = 120; cfg.FeatureSearchOffsetY = 50;
cfg.LauncherWindowPlacement = new() { Monitor = "disconnected-display", Width = 1300 };
LayoutResetService.Reset(cfg);
Check(cfg.FeatureSearchWidth == 300 && cfg.FeatureSearchHeight == 36 && cfg.FeatureSearchOffsetX == 0 && cfg.FeatureSearchOffsetY == 0 && cfg.LauncherWindowPlacement == null, "explicit layout reset clears only geometry");
Check(cfg.HideServerAddresses && cfg.ShowExactCapacityValues && cfg.SelectedVersionId == "keep-instance" && !cfg.AllowCommands, "layout reset retains privacy, preferences, instance and command permissions");
Console.WriteLine($"PASS {count} presentation preference checks");
