using XCL2.App.Models;
using XCL2.App.Services;
static void Check(bool condition, string name) { if (!condition) throw new Exception(name); }
var now = new DateTime(2026, 10, 17, 10, 0, 0, DateTimeKind.Utc);
Check(AccountLoginStatus.Describe(null, now).Contains("尚未选择"), "no account");
var account = new Account();
Check(AccountLoginStatus.Describe(account, now).Contains("无登录有效期"), "offline has no expiry");
account.IsGuest = true;
Check(AccountLoginStatus.Describe(account, now).Contains("本次会话"), "guest lifetime");
account.IsGuest = false; account.Type = AccountType.Microsoft;
Check(AccountLoginStatus.Describe(account, now).Contains("缺少登录凭据"), "missing both credentials");
account.MsRefreshToken = "secret-refresh-token";
Check(AccountLoginStatus.Describe(account, now).Contains("尝试刷新") && !AccountLoginStatus.Describe(account, now).Contains("重新登录"), "refresh credential without access token does not force login");
account.MinecraftAccessToken = "secret-access-token";
Check(AccountLoginStatus.Describe(account, now).Contains("未知"), "unknown expiry remains uncertain");
account.AccessTokenExpiresAtUtc = now;
Check(AccountLoginStatus.Describe(account, now).Contains("已过期") && AccountLoginStatus.Describe(account, now).Contains("尝试刷新"), "expired refreshable");
account.MsRefreshToken = null;
Check(AccountLoginStatus.Describe(account, now).Contains("需要重新登录"), "expired without refresh");
account.AccessTokenExpiresAtUtc = now.AddMinutes(3);
Check(AccountLoginStatus.Describe(account, now).Contains("过期后需要重新登录") && !AccountLoginStatus.Describe(account, now).Contains("尝试刷新"), "soon expiry without refresh does not promise refresh");
account.AccessTokenExpiresAtUtc = now.AddHours(1);
Check(AccountLoginStatus.Describe(account, now).Contains("仍可能撤销"), "cached validity does not guarantee remote authorization");
Check(!AccountLoginStatus.Describe(account, now).Contains("secret-"), "never exposes tokens");
account.Type = AccountType.AuthServer; account.MinecraftAccessToken = null;
Check(AccountLoginStatus.Describe(account, now).Contains("缺少"), "auth server missing credentials");
account.MinecraftAccessToken = "secret-auth-token";
Check(AccountLoginStatus.Describe(account, now).Contains("本地无法判断"), "auth server validity remains uncertain");
Console.WriteLine("Account login status regression checks passed.");
